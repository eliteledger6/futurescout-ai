"""Company fundamentals from the SEC's XBRL "company facts" API (free, needs EDGAR_USER_AGENT).

  GET https://data.sec.gov/api/xbrl/companyfacts/CIK##########.json  (one file per company, 1-5 MB)

Checked live 2026-11-08: facts[taxonomy][concept].units[unit] is a list of reported values; annual
values have fp == "FY" and a frame like "CY2025" (no "Q"). US filers use us-gaap concepts; foreign
filers (20-F) use ifrs-full. Values are USD (or the reporting currency) as reported.

What this adds: the SIZE and trend of a company, computed by code: last annual revenue, revenue
growth, R&D spend and R&D intensity, net income, and a revenue size class. It exists so that a
"discovered" small company is shown as small, with numbers, instead of standing next to Micron as
if comparable. It is not a valuation and says nothing about the share price.
Responses are cached on disk for 24 hours (the files are large). The user agent is the only header.
"""

from __future__ import annotations

import json
import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import Callable, Optional

import httpx

from app.config import BACKEND_DIR
from app.sources.base import RateLimiter, SourceError, get_with_retry

API = "https://data.sec.gov/api/xbrl/companyfacts/CIK{cik:010d}.json"
SOURCE = "SEC XBRL company facts"
CACHE_DIR = BACKEND_DIR / "cache" / "secfacts"
CACHE_TTL_S = 24 * 3600
YEARS = 4

REVENUE_CONCEPTS = [("us-gaap", "RevenueFromContractWithCustomerExcludingAssessedTax"), ("us-gaap", "Revenues"),
                    ("us-gaap", "SalesRevenueNet"), ("ifrs-full", "Revenue")]
RND_CONCEPTS = [("us-gaap", "ResearchAndDevelopmentExpense"), ("ifrs-full", "ResearchAndDevelopmentExpense")]
INCOME_CONCEPTS = [("us-gaap", "NetIncomeLoss"), ("us-gaap", "ProfitLoss"), ("ifrs-full", "ProfitLoss")]

# Revenue size classes (USD, latest fiscal year). A rough, transparent bucket, NOT market capitalisation.
SIZE_CLASSES = [(100e6, "micro"), (1e9, "small"), (10e9, "mid"), (float("inf"), "large")]


@dataclass
class Fundamentals:
    cik: int
    name: str
    currency: str = "USD"
    revenue: dict[int, float] = field(default_factory=dict)       # fiscal year -> annual revenue
    rnd: dict[int, float] = field(default_factory=dict)
    net_income: dict[int, float] = field(default_factory=dict)
    latest_year: Optional[int] = None
    revenue_growth_pct: Optional[float] = None                    # latest FY vs the one before
    rnd_intensity_pct: Optional[float] = None                     # R&D / revenue, latest FY
    size_class: Optional[str] = None                              # micro | small | mid | large (by revenue)
    source_url: str = ""

    def summary(self) -> str:
        """One plain sentence, generated by code (the model may quote it)."""
        if not self.latest_year or self.latest_year not in self.revenue:
            return f"{self.name}: no annual revenue reported in SEC XBRL data."
        rev = self.revenue[self.latest_year]
        size = f" ({self.size_class} by revenue)" if self.size_class else f" (reported in {self.currency}; size class not assigned)"
        parts = [f"{self.name}: fiscal {self.latest_year} revenue {_money(rev, self.currency)}{size}"]
        if self.revenue_growth_pct is not None:
            parts.append(f"revenue growth {self.revenue_growth_pct:+.1f}% vs the prior fiscal year")
        if self.latest_year in self.rnd:
            parts.append(f"R&D {_money(self.rnd[self.latest_year], self.currency)}"
                         + (f" ({self.rnd_intensity_pct:.1f}% of revenue)" if self.rnd_intensity_pct is not None else ""))
        if self.latest_year in self.net_income:
            parts.append(f"net income {_money(self.net_income[self.latest_year], self.currency)}")
        return "; ".join(parts) + "."

    def as_dict(self) -> dict:
        return {"cik": self.cik, "currency": self.currency, "latest_year": self.latest_year,
                "revenue": {str(k): v for k, v in self.revenue.items()}, "rnd": {str(k): v for k, v in self.rnd.items()},
                "net_income": {str(k): v for k, v in self.net_income.items()},
                "revenue_growth_pct": self.revenue_growth_pct, "rnd_intensity_pct": self.rnd_intensity_pct,
                "size_class": self.size_class, "summary": self.summary(), "source_url": self.source_url}


def _money(v: float, cur: str) -> str:
    sign = "-" if v < 0 else ""
    v = abs(v)
    if v >= 1e9:
        return f"{sign}{cur} {v / 1e9:.1f}B"
    if v >= 1e6:
        return f"{sign}{cur} {v / 1e6:.0f}M"
    return f"{sign}{cur} {v:,.0f}"


def _annual_series(facts: dict, concepts: list[tuple[str, str]]) -> tuple[dict[int, float], str]:
    """Fiscal-year values for the first concept that has any, keyed by the frame year (CY2025 -> 2025)."""
    for tax, concept in concepts:
        node = ((facts.get(tax) or {}).get(concept) or {}).get("units") or {}
        if not node:
            continue
        unit = next(iter(node))
        series: dict[int, float] = {}
        for v in node[unit]:
            frame = str(v.get("frame") or "")
            if v.get("fp") == "FY" and frame.startswith("CY") and "Q" not in frame:
                try:
                    series[int(frame[2:6])] = float(v["val"])
                except (KeyError, TypeError, ValueError):
                    continue
        if series:
            years = sorted(series)[-YEARS:]
            return {y: series[y] for y in years}, unit
    return {}, "USD"


def parse_facts(payload: object, cik: int, fallback_name: str) -> Fundamentals:
    if not isinstance(payload, dict) or "facts" not in payload:
        raise SourceError(SOURCE, "company facts response had an unexpected shape")
    facts = payload["facts"] or {}
    f = Fundamentals(cik=cik, name=str(payload.get("entityName") or fallback_name).replace("\xa0", " ").strip(),
                     source_url=API.format(cik=cik))
    f.revenue, f.currency = _annual_series(facts, REVENUE_CONCEPTS)
    f.rnd, _ = _annual_series(facts, RND_CONCEPTS)
    f.net_income, _ = _annual_series(facts, INCOME_CONCEPTS)
    if f.revenue:
        years = sorted(f.revenue)
        f.latest_year = years[-1]
        latest = f.revenue[f.latest_year]
        if len(years) > 1 and f.revenue[years[-2]] > 0:
            f.revenue_growth_pct = round((latest / f.revenue[years[-2]] - 1) * 100, 1)
        if f.latest_year in f.rnd and latest > 0:
            f.rnd_intensity_pct = round(f.rnd[f.latest_year] / latest * 100, 1)
        # the thresholds are USD; a company reporting in another currency gets no class rather than a wrong one
        f.size_class = next(label for limit, label in SIZE_CLASSES if latest < limit) if f.currency == "USD" else None
    return f


class SecFactsClient:
    SOURCE = SOURCE

    def __init__(
        self,
        user_agent: str,
        *,
        http: Optional[httpx.Client] = None,
        limiter: Optional[RateLimiter] = None,
        cache_dir: Optional[Path] = CACHE_DIR,
        sleep: Callable[[float], None] = time.sleep,
        clock: Callable[[], float] = time.time,
    ) -> None:
        if not user_agent or "@" not in user_agent:
            raise SourceError(SOURCE, "EDGAR_USER_AGENT must include a contact email, as the SEC requires")
        self._http = http or httpx.Client(timeout=60.0, headers={"User-Agent": user_agent}, follow_redirects=True)
        self._limiter = limiter or RateLimiter(0.15)
        self._cache_dir, self._sleep, self._clock = cache_dir, sleep, clock
        self.requests = 0

    def fundamentals(self, cik: int, name: str) -> Fundamentals:
        path = self._cache_dir / f"CIK{cik:010d}.json" if self._cache_dir else None
        if path and path.is_file() and self._clock() - path.stat().st_mtime < CACHE_TTL_S:
            return parse_facts(json.loads(path.read_text(encoding="utf-8")), cik, name)
        r = get_with_retry(self._http, API.format(cik=cik), source=SOURCE, sleep=self._sleep, before_request=self._limiter.wait,
                           max_attempts=2, status_hints={404: "no XBRL facts for this company", 403: "SEC refused (check EDGAR_USER_AGENT)"})
        self.requests += 1
        try:
            payload = r.json()
        except ValueError:
            raise SourceError(SOURCE, "response was not JSON") from None
        f = parse_facts(payload, cik, name)
        if path:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(json.dumps(payload), encoding="utf-8")
        return f
