"""Price & timing risk (part of the Risk agent). Owner decision 2026-11-08: show whether NOW looks
stretched or calm for the companies the Market agent found, as a RISK input. Never a buy/sell signal,
never a "correct entry point": nobody can know that, and the platform does not give trading advice.

Everything numeric is computed here by code from real daily prices (Alpha Vantage, last ~100 trading
days on the free plan). The model only explains the computed numbers. Findings ids: T1, T2...

Timing-risk level rules (transparent, initial assumptions, not fitted to data):
  elevated  : 3-month return >= +40%, OR price >= 20% above its 50-day average,
              OR within 3% of the 100-day high after a 1-month rise of >= 15%
  subdued   : price >= 10% below its 50-day average AND 3-month return <= 0
  moderate  : everything else
  + "high volatility" flag when 20-day annualised volatility >= 60%
"Subdued" does NOT mean the price will rise; it only means the recent run-up risk is lower.
"""

from __future__ import annotations

import logging
import math
from datetime import datetime, timezone
from pathlib import Path
from typing import Callable, Optional

from app.graph.citation_guard import apply_citation_guard
from app.models.router import ModelRouter, ModelRouterError
from app.schemas.common import AgentError, ContentType, Label, SourceRecord
from app.schemas.market import MarketResult
from app.schemas.timing import PriceMetrics, PriceTimingResult, TimingReport
from app.sources.base import SourceError
from app.sources.prices import AlphaVantageClient, Bar

log = logging.getLogger("futurescout.timing")
_PROMPT_PATH = Path(__file__).with_name("timing_prompt.md")
MAX_TICKERS = 6          # free plan: 25 requests/day
MIN_BARS = 30


def _pct(a: float, b: float) -> float:
    return round((a / b - 1) * 100, 1)


def compute_metrics(ticker: str, company: str, bars: list[Bar], source_id: str) -> PriceMetrics:
    closes = [b.close for b in bars]
    last = closes[-1]
    r1 = _pct(last, closes[-22]) if len(closes) > 21 else None
    r3 = _pct(last, closes[-64]) if len(closes) > 63 else None
    vs50 = _pct(last, sum(closes[-50:]) / 50) if len(closes) >= 50 else None
    vol = None
    if len(closes) > 20:
        rets = [math.log(closes[i] / closes[i - 1]) for i in range(len(closes) - 20, len(closes))]
        mean = sum(rets) / len(rets)
        vol = round(math.sqrt(sum((x - mean) ** 2 for x in rets) / (len(rets) - 1)) * math.sqrt(252) * 100, 1)
    hi, lo = max(b.high for b in bars), min(b.low for b in bars)
    from_hi, from_lo = _pct(last, hi), _pct(last, lo)

    reasons: list[str] = []
    if r3 is not None and r3 >= 40:
        reasons.append(f"up {r3}% over 3 months")
    if vs50 is not None and vs50 >= 20:
        reasons.append(f"{vs50}% above its 50-day average")
    if from_hi > -3 and r1 is not None and r1 >= 15:
        reasons.append(f"within {abs(from_hi)}% of its {len(bars)}-day high after a {r1}% 1-month rise")
    if reasons:
        level = "elevated"
    elif vs50 is not None and vs50 <= -10 and (r3 is None or r3 <= 0):
        level = "subdued"
        reasons.append(f"{abs(vs50)}% below its 50-day average and {r3 if r3 is not None else 'n/a'}% over 3 months")
    else:
        level = "moderate"
        reasons.append("no stretch or pull-back rule triggered")
    high_vol = vol is not None and vol >= 60
    if high_vol:
        reasons.append(f"high volatility ({vol}% annualised, 20-day)")
    return PriceMetrics(
        ticker=ticker, company=company, source_id=source_id, last_date=bars[-1].day.isoformat(), last_close=round(last, 2),
        bars=len(bars), window_start=bars[0].day.isoformat(), return_1m_pct=r1, return_3m_pct=r3, vs_50d_avg_pct=vs50,
        volatility_20d_pct=vol, from_window_high_pct=from_hi, from_window_low_pct=from_lo,
        timing_risk=level, reasons=reasons, high_volatility=high_vol, closes=[round(c, 2) for c in closes],
    )


def metrics_text(m: PriceMetrics) -> str:
    """Plain sentence, generated by code from the price data; the citation guard checks quotes against it."""
    parts = [f"{m.ticker} closed at {m.last_close} on {m.last_date}."]
    if m.return_1m_pct is not None:
        parts.append(f"1-month return {m.return_1m_pct}%.")
    if m.return_3m_pct is not None:
        parts.append(f"3-month return {m.return_3m_pct}%.")
    if m.vs_50d_avg_pct is not None:
        parts.append(f"Price vs 50-day average {m.vs_50d_avg_pct}%.")
    if m.volatility_20d_pct is not None:
        parts.append(f"20-day annualised volatility {m.volatility_20d_pct}%.")
    parts.append(f"{m.from_window_high_pct}% from the {m.bars}-day high and {m.from_window_low_pct}% from the {m.bars}-day low.")
    parts.append(f"Timing risk (rule-based): {m.timing_risk}: {'; '.join(m.reasons)}.")
    return " ".join(parts)


def tickers_from_market(market: Optional[MarketResult], limit: int = MAX_TICKERS) -> list[tuple[str, str]]:
    """Companies whose filings mention the topic, most mentions first."""
    if not market:
        return []
    # configured companies first (more filings read), then discovered ones; most mentions first within each
    ranked = sorted((c for c in market.companies if c.filings_with_mentions > 0),
                    key=lambda c: (c.discovered, -c.filings_with_mentions))
    return [(c.ticker, c.name) for c in ranked][:limit]


def run_price_timing(
    topic: str,
    market: Optional[MarketResult],
    client: Optional[AlphaVantageClient],
    router: Optional[ModelRouter],
    *,
    now: Callable[[], datetime] = lambda: datetime.now(timezone.utc),
) -> PriceTimingResult:
    result = PriceTimingResult(coverage_note=(
        "Daily closing prices for the companies whose SEC filings mention the topic (Alpha Vantage, last ~100 "
        "trading days: the free plan has no longer history, so there is no 52-week or 200-day view). Metrics and "
        "the timing-risk level are computed by code from fixed rules. This is a risk input, not a buy or sell "
        "signal; past prices do not predict future prices."))
    tickers = tickers_from_market(market)
    if client is None:
        result.limitations = ["Prices were not fetched (ALPHA_VANTAGE_API_KEY not set)."]
        return result
    if not tickers:
        result.limitations = ["No company was identified by the Market agent, so no prices were fetched."]
        return result

    for ticker, company in tickers:
        try:
            bars = client.daily(ticker)
        except SourceError as exc:
            result.errors.append(AgentError(agent="timing", source=exc.source, message=exc.message, recoverable=exc.retryable))
            continue
        if len(bars) < MIN_BARS:
            result.errors.append(AgentError(agent="timing", source=client.SOURCE, message=f"{ticker}: only {len(bars)} days of prices"))
            continue
        rec = SourceRecord(
            url=client.source_url(ticker), source_name=client.SOURCE, content_type=ContentType.OTHER,
            title=f"{company} ({ticker}) daily prices {bars[0].day} to {bars[-1].day}", published_at=bars[-1].day.isoformat(),
            organization=company, publication_type="daily stock prices", text_depth="full_text",
        )
        m = compute_metrics(ticker, company, bars, rec.id)
        result.sources.append(rec.model_copy(update={"abstract": metrics_text(m)}))
        result.metrics.append(m)
    result.requests_used = client.requests

    if not result.metrics:
        result.status = "partial" if result.errors else "no_data"
        result.limitations = ["No price series could be retrieved."]
        return result
    if router is None:
        result.status = "retrieval_only"
        return result

    lines = "\n\n".join(f"id: {s.id}\ncompany: {s.organization}\nmetrics (computed by code): {s.abstract}" for s in result.sources)
    messages = [
        {"role": "system", "content": _PROMPT_PATH.read_text(encoding="utf-8")},
        {"role": "user", "content": f"Topic: {topic}\nToday's date: {now().date().isoformat()}\n\nPrice series ({len(result.sources)}):\n\n{lines}"},
    ]
    try:
        reply = router.complete("timing", messages, response_model=TimingReport)
    except ModelRouterError as exc:
        result.errors.append(AgentError(agent="timing", source="model", message=f"{exc} {exc.attempts}".strip(), recoverable=True))
        result.status = "partial"
        return result
    report: TimingReport = reply.parsed  # type: ignore[assignment]
    guarded = apply_citation_guard(report.findings, {s.id: s for s in result.sources})
    for i, f in enumerate(guarded.findings, start=1):
        f.fid = f"T{i}"
        if f.label == Label.FORECAST:   # price forecasts are not allowed here
            f.label = Label.AI_INTERPRETATION
            f.guard_note = ((f.guard_note + "; ") if f.guard_note else "") + "relabelled: price forecasts are not allowed"
    result.findings = guarded.findings
    result.limitations = report.limitations
    result.llm_alias = reply.llm_alias
    result.status = "ok" if not result.errors else "partial"
    return result
